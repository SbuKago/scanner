-- 1. Create Database
CREATE DATABASE IF NOT EXISTS dispatch_db;
USE dispatch_db;

-- 2. Create Products Table (Product Master)
CREATE TABLE IF NOT EXISTS products (
    product_code VARCHAR(100) PRIMARY KEY,
    barcode VARCHAR(50) NOT NULL,
    description VARCHAR(255) NOT NULL,
    pack_size VARCHAR(50),
    sell_by VARCHAR(50),
    bb_date VARCHAR(50),
    cases_per_pallet INT DEFAULT 0,
    units_per_case INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_barcode (barcode)
);

-- 3. Create Loading History Table (Linked by Product Code)
CREATE TABLE IF NOT EXISTS loading_history (
    id VARCHAR(50) PRIMARY KEY,
    session_id VARCHAR(50),
    timestamp DATETIME NOT NULL,
    truck_reg VARCHAR(50) NOT NULL,
    customer VARCHAR(100) NOT NULL,
    delivery_number VARCHAR(50) NOT NULL,
    route VARCHAR(100),
    product_code VARCHAR(100) NOT NULL,
    barcode VARCHAR(50) NOT NULL,
    cases INT DEFAULT 0,
    quantity INT DEFAULT 0,
    pallet_type VARCHAR(50) DEFAULT 'Standard',
    status VARCHAR(20) DEFAULT 'LOADED',
    loaded_by VARCHAR(100) NOT NULL,
    FOREIGN KEY (product_code) REFERENCES products(product_code) ON DELETE CASCADE
);

-- 4. Create Barcode Problems Table
CREATE TABLE IF NOT EXISTS barcode_problems (
    id VARCHAR(50) PRIMARY KEY,
    timestamp DATETIME NOT NULL,
    barcode VARCHAR(50) NOT NULL,
    problem_type VARCHAR(100) NOT NULL,
    comment TEXT,
    reported_by VARCHAR(100) NOT NULL,
    status VARCHAR(20) DEFAULT 'OPEN'
);

